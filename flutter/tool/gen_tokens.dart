/// CSS custom properties for [tokens]: primitives and light roles on `:root`, dark roles under
/// `prefers-color-scheme: dark` (unless `data-theme="light"`) and `[data-theme="dark"]`, motion
/// set to 0 under `prefers-reduced-motion`.
String generateCss(Tokens tokens) {
  final out = StringBuffer()
    ..writeln('/* GENERATED by flutter/tool/gen_tokens.dart from tokens/tokens.json. Do not edit by hand. */')
    ..writeln('/* Saleba design tokens (docs/CHARTE_GRAPHIQUE.md). */')
    ..writeln()
    ..writeln(':root {');

  void group(String title, List<String> path, String Function(Tokens) emit) {
    Object? node = tokens;
    for (final p in path) {
      node = (node as Tokens)[p];
    }
    out.writeln('  /* $title */');
    _walk(node as Tokens, [], (sub, t) {
      out.writeln('  ${_cssVar([...path, ...sub])}: ${emit(t)};');
    });
  }

  String raw(Tokens t) => _cssValue(tokens, t);

  for (final entry in _groups(tokens['color'] as Tokens)) {
    group('color.${entry.key}', ['color', entry.key], raw);
  }
  for (final name in ['family', 'size', 'weight']) {
    group('font.$name', ['font', name], raw);
  }
  for (final name in ['space', 'radius', 'size', 'shadow', 'motion']) {
    group(name, [name], raw);
  }

  final semantic = tokens['semantic'] as Tokens;
  final modes = _groups(semantic).map((e) => e.key).toList();
  if (modes.join(',') != 'light,dark') {
    throw FormatException('semantic must hold exactly `light` then `dark`, got $modes');
  }
  void roles(String mode, String indent) {
    _walk(semantic[mode] as Tokens, [], (path, t) {
      out.writeln('$indent${_cssVar(path)}: ${_cssValue(tokens, t)};');
    });
  }

  out
    ..writeln('  /* semantic.light (default) */')
    ..writeln('  color-scheme: light;');
  roles('light', '  ');
  out
    ..writeln('}')
    ..writeln()
    ..writeln('@media (prefers-color-scheme: dark) {')
    ..writeln('  :root:not([data-theme="light"]) {')
    ..writeln('    color-scheme: dark;');
  roles('dark', '    ');
  out
    ..writeln('  }')
    ..writeln('}')
    ..writeln()
    ..writeln(':root[data-theme="dark"] {')
    ..writeln('  color-scheme: dark;');
  roles('dark', '  ');
  out
    ..writeln('}')
    ..writeln()
    ..writeln('/* Charter §4: respect "reduce motion". */')
    ..writeln('@media (prefers-reduced-motion: reduce) {')
    ..writeln('  :root {');
  _walk(tokens['motion'] as Tokens, [], (path, t) {
    if (t[r'$type'] == 'duration') out.writeln('    ${_cssVar(['motion', ...path])}: 0ms;');
  });
  out
    ..writeln('  }')
    ..writeln('}');
  return out.toString();
}

/// Tailwind CSS v4 theme (`@theme inline`) pointing at the custom properties of [generateCss], so
/// that utilities follow the light / dark switch.
String generateTailwind(Tokens tokens) {
  final out = StringBuffer()
    ..writeln('/* GENERATED by flutter/tool/gen_tokens.dart from tokens/tokens.json. Do not edit by hand. */')
    ..writeln('/* Tailwind CSS v4: @import "tailwindcss"; @import "@saleba/design/tailwind.css"; */')
    ..writeln()
    ..writeln('@import "./saleba-tokens.css";')
    ..writeln()
    ..writeln('@theme inline {');

  void map(
    String namespace,
    List<String> path, {
    String Function(List<String>)? rename,
    List<String>? varPath,
  }) {
    Object? node = tokens;
    for (final p in path) {
      node = (node as Tokens)[p];
    }
    _walk(node as Tokens, [], (sub, t) {
      final name = rename?.call(sub) ?? sub.join('-');
      out.writeln('  --$namespace-$name: var(${_cssVar([...(varPath ?? path), ...sub])});');
    });
  }

  out
    ..writeln('  /* Charter §7: no colour outside the tokens, so the default Tailwind palette is removed. */')
    ..writeln('  --color-*: initial;')
    ..writeln('  /* Roles: switch with the theme (bg-surface, text-text-muted, bg-primary…) */');
  map('color', ['semantic', 'light'], varPath: []);
  out.writeln('  /* Primitives */');
  for (final entry in _groups(tokens['color'] as Tokens)) {
    map('color', ['color', entry.key], rename: (sub) => [entry.key, ...sub].join('-'));
  }
  map('font', ['font', 'family']);
  map('text', ['font', 'size']);
  map('font-weight', ['font', 'weight']);
  map('spacing', ['space']);
  map('radius', ['radius']);
  map('shadow', ['shadow']);
  out
    ..writeln('  --ease-saleba: var(--saleba-motion-ease);')
    ..writeln('}');
  return out.toString();
}

/// `--saleba-<path>`: primitives keep their full path (`--saleba-color-brand-primary`), semantic
/// roles are called with their role only (`--saleba-bg`).
String _cssVar(List<String> path) => '--saleba-${path.join('-')}';

String _cssValue(Tokens tokens, Tokens t) {
  final value = t[r'$value'];
  if (value is String && value.startsWith('{')) {
    return 'var(${_cssVar(value.substring(1, value.length - 1).split('.'))})';
  }
  return switch (t[r'$type']) {
    'color' => (value as String).toUpperCase(),
    'fontFamily' => _families(value).map((f) => _genericFamilies.contains(f) ? f : '"$f"').join(', '),
    'shadow' => () {
      final s = value as Tokens;
      return '${s['offsetX']} ${s['offsetY']} ${s['blur']} ${s['spread']} '
          '${(_resolve(tokens, s['color']) as String).toUpperCase()}';
    }(),
    'cubicBezier' => 'cubic-bezier(${(value as List).join(', ')})',
    _ => '$value',
  };
}

// ---------------------------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------------------------

const _genericFamilies = {'serif', 'sans-serif', 'monospace', 'cursive', 'fantasy', 'system-ui'};

Iterable<MapEntry<String, Tokens>> _groups(Tokens group) =>
    group.entries.where((e) => !e.key.startsWith(r'$')).map((e) => MapEntry(e.key, e.value as Tokens));

void _walk(Tokens group, List<String> path, void Function(List<String>, Tokens) visit) {
  for (final entry in group.entries) {
    if (entry.key.startsWith(r'$')) continue;
    final value = entry.value;
    if (value is! Tokens) continue;
    final next = [...path, entry.key];
    if (value.containsKey(r'$value')) {
      visit(next, value);
    } else {
      _walk(value, next, visit);
    }
  }
}

List<List<String>> _leaves(Tokens group) {
  final paths = <List<String>>[];
  _walk(group, [], (path, _) => paths.add(path));
  return paths;
}

/// Follows `{color.neutral.25}` references.
Object? _resolve(Tokens tokens, Object? value) {
  var current = value;
  for (var depth = 0; current is String && current.startsWith('{'); depth++) {
    if (depth > 10) throw FormatException('reference cycle at $value');
    Object? node = tokens;
    for (final part in current.substring(1, current.length - 1).split('.')) {
      node = (node as Tokens)[part];
      if (node == null) throw FormatException('unknown token reference $current');
    }
    current = (node as Tokens)[r'$value'];
  }
  return current;
}

/// `#RRGGBB` or `#RRGGBBAA` → `Color(0xAARRGGBB)`.
String _dartColor(Object? value) {
  final hex = (value as String).substring(1).toUpperCase();
  final argb = switch (hex.length) {
    6 => 'FF$hex',
    8 => '${hex.substring(6)}${hex.substring(0, 6)}',
    _ => throw FormatException('invalid colour $value'),
  };
  return 'Color(0x$argb)';
}

List<String> _families(Object? value) => switch (value) {
  String s => [s],
  List l => l.cast<String>(),
  _ => throw FormatException('invalid font family $value'),
};

String _px(Object? value) => '${double.parse((value as String).replaceFirst('px', ''))}';

int _ms(Object? value) => int.parse((value as String).replaceFirst('ms', ''));

List<double> _bezier(Object? value) => (value as List).map((v) => (v as num).toDouble()).toList();

String _camel(List<String> parts) {
  final words = parts.expand((p) => p.split('-')).where((w) => w.isNotEmpty).toList();
  return [
    for (var i = 0; i < words.length; i++)
      i == 0 ? words[i] : '${words[i][0].toUpperCase()}${words[i].substring(1)}',
  ].join();
}
