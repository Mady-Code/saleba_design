/// Dart source of the `SalebaTokens` class for [tokens].
///
/// Names match the generator of saleba-front-mobile (PR 15) so that the app can switch to this
/// package without renaming anything.
String generateDart(Tokens tokens) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/gen_tokens.dart from tokens/tokens.json. Do not edit by hand.')
    ..writeln()
    ..writeln("import 'package:flutter/widgets.dart';")
    ..writeln()
    ..writeln('/// Saleba design tokens (docs/CHARTE_GRAPHIQUE.md). The only place where colour values')
    ..writeln('/// are written in the Saleba Flutter code.')
    ..writeln('abstract final class SalebaTokens {');

  void section(String title, Tokens group, String prefix, String Function(Tokens) emit) {
    out
      ..writeln()
      ..writeln('  // $title');
    _walk(group, [], (path, token) {
      final name = _camel([prefix, ...path]);
      final description = token[r'$description'];
      if (description is String) out.writeln('  /// $description');
      out.writeln('  static const ${emit(token)}'.replaceFirst('§', name));
    });
  }

  String color(Tokens t) => 'Color § = ${_dartColor(_resolve(tokens, t[r'$value']))};';
  String px(Tokens t) => 'double § = ${_px(t[r'$value'])};';

  final colorGroup = tokens['color'] as Tokens;
  for (final entry in _groups(colorGroup)) {
    // `color.brand.primary` → `brandPrimary`, `color.feedback.success` → `success`.
    final prefix = entry.key == 'feedback' ? '' : entry.key;
    section('color.${entry.key}', entry.value, prefix, color);
  }
  final data = colorGroup['data'] as Tokens?;
  if (data != null) {
    final names = _leaves(data).map((p) => _camel(['data', ...p])).join(', ');
    out
      ..writeln('  /// Categorical palette (charts, avatars, categories), always in this order.')
      ..writeln('  static const List<Color> dataPalette = [$names];');
  }
  for (final entry in _groups(tokens['semantic'] as Tokens)) {
    section('semantic.${entry.key}', entry.value, entry.key, color);
  }

  final font = tokens['font'] as Tokens;
  section('font.family', font['family'] as Tokens, 'fontFamily', (t) {
    final families = _families(t[r'$value']);
    return "String § = '${families.first}';";
  });
  // Fallbacks without CSS generic families (`sans-serif`…), which Flutter does not know.
  _walk(font['family'] as Tokens, [], (path, t) {
    final fallback = _families(t[r'$value']).skip(1).where((f) => !_genericFamilies.contains(f));
    out.writeln(
      "  static const List<String> ${_camel(['fontFamily', ...path, 'fallback'])} = [${fallback.map((f) => "'$f'").join(', ')}];",
    );
  });
  section('font.size', font['size'] as Tokens, 'fontSize', px);
  section(
    'font.weight',
    font['weight'] as Tokens,
    'fontWeight',
    (t) => 'FontWeight § = FontWeight.w${t[r'$value']};',
  );

  section('space', tokens['space'] as Tokens, 'space', px);
  section('radius', tokens['radius'] as Tokens, 'radius', px);
  section('size', tokens['size'] as Tokens, 'size', px);
  section('shadow', tokens['shadow'] as Tokens, 'shadow', (t) {
    final s = t[r'$value'] as Tokens;
    return 'List<BoxShadow> § = [BoxShadow(color: ${_dartColor(_resolve(tokens, s['color']))}, '
        'offset: Offset(${_px(s['offsetX'])}, ${_px(s['offsetY'])}), '
        'blurRadius: ${_px(s['blur'])}, spreadRadius: ${_px(s['spread'])})];';
  });
  section('motion', tokens['motion'] as Tokens, 'motion', (t) {
    final value = t[r'$value'];
    if (t[r'$type'] == 'duration') return 'Duration § = Duration(milliseconds: ${_ms(value)});';
    return 'Cubic § = Cubic(${_bezier(value).join(', ')});';
  });
  out.writeln('}');
  return out.toString();
}

