// Generates every platform output of the Saleba design tokens from tokens/tokens.json (W3C DTCG).
//
//   cd flutter && dart run tool/gen_tokens.dart
//
// Outputs (all committed, never edited by hand):
//   flutter/lib/src/saleba_tokens.dart  Dart constants (Flutter apps: Pro, Market, TV, Admin)
//   web/saleba-tokens.css               CSS custom properties, light + dark + reduced motion
//   web/saleba-tailwind.css             Tailwind CSS v4 theme mapped on those properties
//
// test/generated_test.dart fails when one of them is stale.
import 'dart:convert';
import 'dart:io';

const tokensPath = '../tokens/tokens.json';
const dartOutputPath = 'lib/src/saleba_tokens.dart';
const cssOutputPath = '../web/saleba-tokens.css';
const tailwindOutputPath = '../web/saleba-tailwind.css';

typedef Tokens = Map<String, Object?>;

void main() {
  final tokens = readTokens();
  File(dartOutputPath).writeAsStringSync(generateDart(tokens));
  File(cssOutputPath).writeAsStringSync(generateCss(tokens));
  File(tailwindOutputPath).writeAsStringSync(generateTailwind(tokens));
  stdout.writeln('Wrote $dartOutputPath, $cssOutputPath, $tailwindOutputPath');
}

Tokens readTokens() => jsonDecode(File(tokensPath).readAsStringSync()) as Tokens;

